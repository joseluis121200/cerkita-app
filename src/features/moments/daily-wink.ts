export function winkOfTheDay(date: Date = new Date()): string {
  const start = Date.UTC(date.getUTCFullYear(), 0, 0);
  const dayOfYear = Math.floor((date.getTime() - start) / 86_400_000);
  return DAILY_WINKS[dayOfYear % DAILY_WINKS.length] ?? DAILY_WINKS[0];
}
